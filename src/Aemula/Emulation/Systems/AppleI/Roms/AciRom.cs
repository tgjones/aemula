namespace Aemula.Emulation.Systems.AppleI.Roms;

// The Apple Cassette Interface (ACI) firmware, written by Steve Wozniak around
// 1976 - the whole of the optional cassette card's software. On real hardware
// it is two 256x4 bipolar PROMs on the card forming one 256-byte image at
// $C100-$C1FF; the two-PROM split is a hardware width limitation with no
// emulation consequence, so it's a single flat array here, inlined as data
// rather than a binary asset, exactly like WozMonitor.Image.
//
// Not an original dump of these specific bytes: assembled from the widely
// published wozaci.s source (jefftranter/6502's copy, itself transcribed from
// Woz's original listing) and spot-checked instruction-by-instruction against
// that listing - the '*' tape prompt, TAPEIN at $C081, the FLIP output
// flip-flop toggled by any access to $C000-$C0FF, ESCAPE back to the Monitor
// at $FF1A, ECHO at $FFEF. Same sourcing-disclaimer precedent as
// WozMonitor.Image.
//
// The card decodes $C000-$C1FF off the expansion connector. $C100-$C1FF reads
// this image directly. $C000-$C0FF is I/O: every access toggles the tape-out
// flip-flop, and on a read the tape-input comparator's (synchronised) output
// replaces PROM address line A0, so a read of TAPEIN ($C081) returns
// Image[$80] or Image[$81] depending on the live tape level - the firmware
// polls it and watches the byte change. The FSK bit timing is entirely
// software (WDELAY delay loops); the card has no timing one-shot of its own.
