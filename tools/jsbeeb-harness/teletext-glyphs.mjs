#!/usr/bin/env node
// Writes the SAA5050's character set as a C# source file, from the glyph data jsbeeb took from b-em.
//
//   node teletext-glyphs.mjs <output .cs file>
//
// Each of the 96 characters (&20-&7F) is 10 rows; a row is 6 bits, bit 0 the leftmost dot.
import { writeFileSync } from "node:fs";
import { makeChars } from "jsbeeb/src/teletext_data.js";

const chars = makeChars();
const lines = [];
for (let c = 0; c < 96; c++) {
    const rows = [];
    for (let row = 0; row < 10; row++) {
        let bits = 0;
        for (let x = 0; x < 6; x++) bits |= chars[c * 60 + row * 6 + x] << x;
        rows.push("0x" + bits.toString(16).padStart(2, "0"));
    }
    lines.push(`        ${rows.join(", ")}, // &${(c + 0x20).toString(16).toUpperCase()}`);
}

const source = `using System;

namespace Aemula.Emulation.Chips.Saa5050;

// Generated by tools/jsbeeb-harness/teletext-glyphs.mjs.
internal static class Saa5050CharacterRom
{
    /// <summary>
    /// The SAA5050's (English) character generator: the glyphs of codes &amp;20-&amp;7F, ten rows of six
    /// dots each. Bit 0 of a row is its leftmost dot.
    /// </summary>
    public static ReadOnlySpan<byte> Glyphs =>
    [
${lines.join("\n")}
    ];
}
`;
writeFileSync(process.argv[2], source);
