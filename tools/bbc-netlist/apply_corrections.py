#!/usr/bin/env python3
"""Layer the known schematic corrections on top of a raw extraction.

    python3 apply_corrections.py /tmp/bbc-raw/netlist.txt ../../src/Aemula/Emulation/Systems/BbcMicro/docs/bbc-netlist.txt

Corrections are pin-based (never keyed on auto-generated _Nnnn names, which renumber when the
extraction changes). Each one is checked against the raw netlist first, so a regenerated
extraction that no longer matches what a correction expects fails loudly instead of corrupting
the result.
"""
import re
import sys

HEADER = [
    '# BBC Micro Issue 7 netlist, extracted from "bbc_micro_mainboard_iss7_20210909.pdf" (amb5l).',
    '# Generated by tools/bbc-netlist/extract.py from the PDF vector geometry + text layer, not by OCR,',
    '# then corrected by tools/bbc-netlist/apply_corrections.py (the CORRECTIONS list below).',
    '# Format: COMPONENT lines: ref | type | value.  NET lines: netname: ref.pin ref.pin ...',
    '# A leading / means the label is overbarred (active low). Auto-named nets start with _N.',
    '# Gate packages are drawn as separate symbols that share an IC number; sections are told apart by pin number.',
    '# Bus connectivity (A0-A15, D0-D7, ...) is by label, not by wire.',
    '# Rails: +5V also carries the VCC/VCC1-3/VRR labels, 0V also carries GND/VSS.',
    '#',
    '# CORRECTIONS (known errors in the source schematic; stardot thread t=23329):',
    '#   IC93 (75159, RS423 driver), per Tom\'s report checked against TobyLobster\'s vector diagram:',
    '#     IC93A pins 4/5 and IC93B pins 10/11 were labelled the wrong way round. The signal input is',
    '#     IC93A.4 / IC93B.11 and the tied-high input is IC93A.5 / IC93B.10. That signal wire is TxD',
    '#     (IC89.6), not RTS (IC89.2 / IC91A.1,2).',
    '#   IC27 (7438) pins 9 and 10 are transposed: pin 10 is tied to +5V (R65 pull-up), pin 9 takes the',
    '#     8271 INT / S9 net. (Logically a no-op on a NAND, but the pins are now as on the service manual.)',
    '#   IC2 (6845): the symbol numbers /CS as pin 25 and E as pin 23; on the HD6845SP /CS is pin 23 and E',
    '#     is pin 25, so the two pins\' nets are exchanged (CRTC# on 23, 1MHZE on 25).',
    '#   Keyboard "spurious extra wire": reported against TobyLobster\'s own diagram, which he fixed.',
    '#     It is not an error of this schematic, so nothing is applied for it.',
    '#   Extractor fix, not a schematic error: a +5V symbol drawn with its label further than 3pt from the',
    '#     bar (R65.1) was left unattached; the rail labels now reach 3.5pt.',
    '#   Extractor fix, not a schematic error: the 1MHZE arrow on the 6845 E pin was attached to the',
    '#     neighbouring DEN pin\'s wire, whose corner lay under the label; an arrow tip level with the',
    '#     start of its label now wins.',
    '#   Extractor fixes, not schematic errors: IC20A was swallowed by the rotated A8/A9 bus labels beside it',
    '#     (taken for a decoupling-capacitor reference) and A8/A9 landed on the wrong wires; +5V written as a',
    '#     plain label (IC22.2/.4, IC42.1/.7/.10) was left unattached; one wire is drawn with a 1.5pt break',
    '#     (IC40.6 to IC38.4) and is now joined.',
    '#',
    '# OPEN (drawn that way on the sheet, not corrected; for the user verification passes):',
    '#   IC31.12 (74LS74 D, the second half of the 1 MHz synchroniser) is drawn with no wire at all.',
    '#   IC97B (spare 74LS74 section) has all inputs open; the sheet notes "INPUTS SHOULD BE TIED...".',
    '#',
]

# ('move', pin, destination)    destination is a net name or a pin whose net it joins
# ('swap', pin, pin)            exchange the nets of two pins
CORRECTIONS = [
    ('move', 'IC93.5', '+5V'),
    ('move', 'IC93.4', 'IC89.6'),
    ('move', 'IC93.10', '+5V'),
    ('move', 'IC93.11', 'IC89.6'),
    ('swap', 'IC27.9', 'IC27.10'),
    ('swap', 'IC2.23', 'IC2.25'),
]

# state each correction expects of the raw extraction: pin -> net it must currently be on
# (a pin, whose net is then resolved, or a net name)
EXPECT = {
    'IC93.5': 'IC89.2',
    'IC93.4': '+5V',
    'IC93.10': 'IC89.6',
    'IC93.11': '+5V',
    'IC27.9': '+5V',
    'IC27.10': 'IC78.11',
    'IC2.25': 'CRTC#',
    'IC2.23': '1MHZE',
}


def ref_sort(r):
    m = re.match(r'^([A-Z?]+)(\d*)', r)
    return (m.group(1), int(m.group(2) or 0))


def main():
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src).read().split('\n')
    i_nets = text.index('## NETS')
    i_diag = next(i for i, l in enumerate(text) if l.startswith('## DIAGNOSTICS'))
    comps = text[text.index('## COMPONENTS'):i_nets]
    diag = text[i_diag:]
    nets = {}
    pin_net = {}
    for l in text[i_nets + 1:i_diag]:
        if not l.strip():
            continue
        name, pins = l.split(': ', 1)
        nets[name] = set(pins.split())
        for p in nets[name]:
            pin_net[p] = name

    def resolve(x):
        return x if x in nets else pin_net[x]

    for pin, want in EXPECT.items():
        if pin_net.get(pin) != resolve(want):
            sys.exit(f'raw extraction no longer matches: {pin} is on {pin_net.get(pin)}, expected the net of {want}')

    for op, a, b in CORRECTIONS:
        if op == 'move':
            dest = resolve(b)
            nets[pin_net[a]].discard(a)
            nets[dest].add(a)
            pin_net[a] = dest
        else:
            na, nb = pin_net[a], pin_net[b]
            nets[na].discard(a)
            nets[nb].discard(b)
            nets[na].add(b)
            nets[nb].add(a)
            pin_net[a], pin_net[b] = nb, na

    out = list(HEADER) + comps + ['## NETS']
    for nm in sorted((n for n in nets if nets[n]), key=lambda s: (s.startswith('_N'), s.lstrip('/').lower())):
        out.append(f'{nm}: ' + ' '.join(sorted(nets[nm], key=lambda s: (ref_sort(s.split('.')[0]), s))))
    out.append('')
    out.append('## DIAGNOSTICS (extractor output on the uncorrected extraction; net names are the raw ones)')
    out += diag[1:]
    import os
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    open(dst, 'w').write('\n'.join(out).rstrip('\n') + '\n')


if __name__ == '__main__':
    main()
